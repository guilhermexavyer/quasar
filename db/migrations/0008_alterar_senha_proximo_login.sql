-- Quasar: "Alterar senha no próximo login" (Administração do Sistema > Parâmetros).
--
-- 1. Parâmetro em tabela própria, com um único registro (como os demais
--    parâmetros): ie_regra 'S' = Sim; 'N' ou vazio (---) = Não.
-- 2. usuario.ie_alterar_senha: 'S' quando a senha do usuário foi alterada por
--    outra pessoa (menu de contexto "Alterar senha") com o parâmetro em Sim.
--    No login, esse usuário troca a senha antes de entrar; a marca sai quando
--    ele mesmo define a nova senha. Coluna gravada só pelo servidor.

create table as_param_alterar_senha_proximo_login (
  nr_sequencia         bigint generated by default as identity primary key check (nr_sequencia = 1),
  ds_regra             text,
  cd_cor               text,
  ie_regra             text,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

alter table usuario add column ie_alterar_senha text check (ie_alterar_senha in ('S'));

-- Acesso: só o servidor (driver pg), como as demais tabelas.
alter table as_param_alterar_senha_proximo_login enable row level security;
revoke all on as_param_alterar_senha_proximo_login from anon, authenticated;
revoke all on sequence as_param_alterar_senha_proximo_login_nr_sequencia_seq from anon, authenticated;
