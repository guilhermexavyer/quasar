-- Quasar: preferências de colunas das tabelas de registros em tabela própria.
--
-- Antes, a largura e a ordem das colunas de cada lista ficavam em ~50 colunas
-- config_colunas_* da tabela usuario. Agora cada lista de cada usuário é uma
-- linha de usuario_coluna:
--   ie_tabela      → identificador da lista na tela (o sufixo do antigo
--                    config_colunas_*, ex.: pessoa_fisica, lookup_cidade, cg_sexo);
--   config_colunas → a configuração salva (ordem e larguras), em jsonb.
-- A API continua entregando config_colunas_<ie_tabela> no objeto do usuário,
-- então as telas não mudam.
--
-- As preferências pertencem ao usuário: ao excluí-lo, elas saem junto (cascade).
-- Os dados existentes em usuario.config_colunas_* são copiados antes de as
-- colunas antigas serem removidas.

create table usuario_coluna (
  nr_sequencia         bigint generated by default as identity primary key,
  nr_seq_usuario       bigint not null references usuario (nr_sequencia) on delete cascade,
  ie_tabela            text   not null check (ie_tabela ~ '^[a-z0-9_]+$'),
  config_colunas       jsonb  not null,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text,
  unique (nr_seq_usuario, ie_tabela)
);

do $$
declare
  coluna text;
begin
  for coluna in
    select column_name from information_schema.columns
     where table_schema = 'public' and table_name = 'usuario' and column_name like 'config\_colunas\_%'
     order by column_name
  loop
    execute format(
      'insert into usuario_coluna (nr_seq_usuario, ie_tabela, config_colunas, dt_criacao, dt_alteracao, ds_usuario_criacao, ds_usuario_alteracao)
       select nr_sequencia, %L, %I, now(), now(), ds_usuario, ds_usuario from usuario where %I is not null',
      substr(coluna, length('config_colunas_') + 1), coluna, coluna
    );
    execute format('alter table usuario drop column %I', coluna);
  end loop;
end $$;

alter table usuario_coluna enable row level security;
revoke all on usuario_coluna from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;
