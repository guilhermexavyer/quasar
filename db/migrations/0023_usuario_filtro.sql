-- Quasar: filtros salvos pelo usuário (botão "Salvar filtro" dos modais de filtro).
--
-- Cada tela de registros de cada usuário é uma linha de usuario_filtro, como as
-- preferências de colunas (usuario_coluna) e de painéis (usuario_painel):
--   ie_tela        → identificador da tela (ex.: pessoa_fisica, pat_ativo, logs_acessos);
--   config_filtro  → os campos do filtro salvo, em jsonb.
-- A API entrega config_filtro_<ie_tela> no objeto do usuário (login e sessão); ao abrir
-- o sistema, o filtro salvo de cada tela já vem aplicado.
--
-- Os filtros pertencem ao usuário: ao excluí-lo, eles saem junto (cascade).

create table usuario_filtro (
  nr_sequencia         bigint generated by default as identity primary key,
  nr_seq_usuario       bigint not null references usuario (nr_sequencia) on delete cascade,
  ie_tela              text   not null check (ie_tela ~ '^[a-z0-9_]+$'),
  config_filtro        jsonb  not null,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text,
  unique (nr_seq_usuario, ie_tela)
);

-- Acesso: só o servidor (driver pg), como as demais tabelas.
alter table usuario_filtro enable row level security;
revoke all on usuario_filtro from anon, authenticated;
revoke all on sequence usuario_filtro_nr_sequencia_seq from anon, authenticated;
