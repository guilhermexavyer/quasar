-- Quasar: Estrutura Acadêmica > Turmas e Disciplinas; Cadastros Gerais > Modalidade de ensino.
--
--   cg_modalidade_ensino: Sequência, Descrição e Status (como os demais Cadastros Gerais);
--   disciplina:           Sequência, Descrição e Observação;
--   turma:                Sequência, Descrição, Curso, Período letivo, Máximo de alunos,
--                         Localização e Modalidade de ensino.
-- Todas com os campos de controle (criação/alteração e usuários). As referências da
-- turma usam on delete restrict: um curso/período/localização/modalidade em uso por
-- uma turma não pode ser excluído.

create table cg_modalidade_ensino (
  nr_sequencia         bigint generated by default as identity primary key,
  ds_modalidade_ensino text,
  ie_status            text check (ie_status in ('A', 'I')),
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

create table disciplina (
  nr_sequencia         bigint generated by default as identity primary key,
  ds_disciplina        text,
  ds_observacao        text,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

create table turma (
  nr_sequencia             bigint generated by default as identity primary key,
  ds_turma                 text,
  nr_seq_curso             bigint references curso (nr_sequencia) on delete restrict,
  nr_seq_periodo_letivo    bigint references periodo_letivo (nr_sequencia) on delete restrict,
  qt_max_alunos            integer check (qt_max_alunos is null or qt_max_alunos >= 0),
  nr_seq_localizacao       bigint references cg_localizacao (nr_sequencia) on delete restrict,
  nr_seq_modalidade_ensino bigint references cg_modalidade_ensino (nr_sequencia) on delete restrict,
  dt_criacao               timestamptz,
  dt_alteracao             timestamptz,
  ds_usuario_criacao       text,
  ds_usuario_alteracao     text
);
create index turma_nr_seq_curso_idx on turma (nr_seq_curso);
create index turma_nr_seq_periodo_letivo_idx on turma (nr_seq_periodo_letivo);
create index turma_nr_seq_localizacao_idx on turma (nr_seq_localizacao);
create index turma_nr_seq_modalidade_ensino_idx on turma (nr_seq_modalidade_ensino);

-- Acesso: só o servidor (driver pg), como as demais tabelas.
alter table cg_modalidade_ensino enable row level security;
alter table disciplina enable row level security;
alter table turma enable row level security;
revoke all on cg_modalidade_ensino, disciplina, turma from anon, authenticated;
revoke all on sequence cg_modalidade_ensino_nr_sequencia_seq, disciplina_nr_sequencia_seq, turma_nr_sequencia_seq from anon, authenticated;
