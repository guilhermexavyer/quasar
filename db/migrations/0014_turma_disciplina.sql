-- Quasar: Estrutura Acadêmica.
--
--   * Turmas: o campo Máximo de alunos sai (passa para Turmas x Disciplinas).
--   * Turmas x Disciplinas (turma_disciplina): as turmas que de fato serão usadas no
--     restante do sistema (ex.: é nelas que os alunos serão incluídos). Campos:
--     Sequência, Turma, Disciplina, Máximo de alunos, Status e os campos de controle.
--     Turma e Disciplina usam on delete restrict: em uso, não podem ser excluídas.

alter table turma drop column if exists qt_max_alunos;

-- Regra de campo do Máximo de alunos da turma (Campos x Formulários) deixa de existir.
update perfil
   set config_campos = config_campos - 'turma.qt_max_alunos'
 where jsonb_typeof(config_campos) = 'object' and config_campos ? 'turma.qt_max_alunos';

create table turma_disciplina (
  nr_sequencia         bigint generated by default as identity primary key,
  nr_seq_turma         bigint references turma (nr_sequencia) on delete restrict,
  nr_seq_disciplina    bigint references disciplina (nr_sequencia) on delete restrict,
  qt_maxima_alunos     integer check (qt_maxima_alunos is null or qt_maxima_alunos >= 0),
  ie_status            text check (ie_status in ('A', 'I')),
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);
create index turma_disciplina_nr_seq_turma_idx on turma_disciplina (nr_seq_turma);
create index turma_disciplina_nr_seq_disciplina_idx on turma_disciplina (nr_seq_disciplina);

-- Acesso: só o servidor (driver pg), como as demais tabelas.
alter table turma_disciplina enable row level security;
revoke all on turma_disciplina from anon, authenticated;
revoke all on sequence turma_disciplina_nr_sequencia_seq from anon, authenticated;
