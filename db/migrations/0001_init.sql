-- Quasar: esquema inicial no PostgreSQL (Supabase).
-- Uma tabela por coleção do Firestore, com o mesmo nome e os mesmos nomes de campo.
--
-- Convenções:
--   * Nenhuma tabela tem coluna "id": a chave primária é sempre nr_sequencia.
--   * nr_sequencia é IDENTITY (sequência atômica do PostgreSQL), no lugar de _counters.
--   * nr_seq_* são chaves estrangeiras com ON DELETE RESTRICT: excluir um registro
--     em uso por outro dá erro.
--   * Datas sem hora são "date"; a API converte de/para 'DD/MM/AAAA', como a tela usa.
--     dt_criacao, dt_alteracao e demais instantes são "timestamptz" (a API devolve ISO).
--   * config_* que eram JSON em texto são "jsonb".
--   * Campos em camelCase (do construtor de relatórios) mantêm o nome exato, entre aspas.
--   * Todas as tabelas têm RLS ligada e nenhum acesso para anon/authenticated: o Data
--     API da Supabase não enxerga nada. Só o servidor acessa, pelo driver pg.
--
-- Aplicado uma única vez por scripts/migrar-esquema.mjs.

