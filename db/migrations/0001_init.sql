-- Sessão de login: o cookie guarda um token aleatório e o banco só o hash dele.
create table sessao (
  nr_sequencia   bigint generated by default as identity primary key,
  ds_token_hash  text not null unique,
  nr_seq_usuario bigint not null references usuario (nr_sequencia) on delete cascade,
  dt_criacao     timestamptz not null default now(),
  dt_expiracao   timestamptz not null
);
create index sessao_nr_seq_usuario_idx on sessao (nr_seq_usuario);

-- Cópia de cada registro excluído (Administração do Sistema > Exclusões).
-- nr_seq_registro, nr_seq_usuario e nr_seq_perfil_exclusao não têm FK: são histórico
-- e precisam sobreviver à exclusão do registro, do usuário e do perfil.
create table exclusao (
  nr_sequencia           bigint generated by default as identity primary key,
  ds_colecao             text not null,
  nr_seq_registro        bigint,
  dados                  jsonb not null,
  dt_exclusao            timestamptz not null,
  ds_usuario_exclusao    text,
  nr_seq_usuario         bigint,
  nr_seq_perfil_exclusao bigint,
  ds_perfil_exclusao     text
);
create index exclusao_ds_colecao_idx on exclusao (ds_colecao, dt_exclusao desc);

-- Trilha de auditoria de todas as tabelas (antes: subcoleção "auditoria" de cada documento).
-- campo/regra dizem qual aviso ou regra foi alterado (aviso e regra têm um registro só).
create table auditoria (
  nr_sequencia    bigint generated by default as identity primary key,
  ds_colecao      text not null,
  nr_seq_registro bigint not null,
  nr_seq_usuario  bigint,
  usuario_nome    text,
  acao            text not null check (acao in ('create', 'update', 'password')),
  "timestamp"     timestamptz not null,
  detalhes        jsonb,
  campo           text,
  regra           text
);
create index auditoria_registro_idx on auditoria (ds_colecao, nr_seq_registro, "timestamp" desc);

