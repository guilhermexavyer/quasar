-- Quasar: nova função Controle de Cópias (departamento de Xerox).
--
--   cg_formato_papel: Cadastros Gerais > Formato do papel (Sequência, Descrição e Status);
--   cg_tipo_papel:    Cadastros Gerais > Tipo de papel (Sequência, Descrição e Status);
--   copia:            Controle de Cópias > Cópias — Solicitante (colaborador), Turma x Disciplina,
--                     Cópias, Folhas, Frente e verso, Grampeado, Formato do papel, Tipo de papel e
--                     Arquivo (caminho no bucket privado "copias" do Storage);
--   cc_param_tipos_arquivo_copia: parâmetro "Tipos de arquivo para anexar em 'Cópias'"
--                     (um único registro, como os demais parâmetros). As extensões permitidas
--                     ficam em ds_regra, separadas por vírgula (ex.: "pdf,docx").
-- Todas com os campos de controle (criação/alteração e usuários). As referências usam
-- on delete restrict: um registro em uso por uma cópia não pode ser excluído.

create table cg_formato_papel (
  nr_sequencia         bigint generated by default as identity primary key,
  ds_formato_papel     text,
  ie_status            text check (ie_status in ('A', 'I')),
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

create table cg_tipo_papel (
  nr_sequencia         bigint generated by default as identity primary key,
  ds_tipo_papel        text,
  ie_status            text check (ie_status in ('A', 'I')),
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

create table copia (
  nr_sequencia            bigint generated by default as identity primary key,
  nr_seq_solicitante      bigint references colaborador (nr_sequencia) on delete restrict,
  nr_seq_turma_disciplina bigint references turma_disciplina (nr_sequencia) on delete restrict,
  qt_copias               integer check (qt_copias is null or qt_copias >= 0),
  qt_folhas               integer check (qt_folhas is null or qt_folhas >= 0),
  ie_frente_verso         text check (ie_frente_verso in ('S', 'N')),
  ie_grampeado            text check (ie_grampeado in ('S', 'N')),
  nr_seq_formato_papel    bigint references cg_formato_papel (nr_sequencia) on delete restrict,
  nr_seq_tipo_papel       bigint references cg_tipo_papel (nr_sequencia) on delete restrict,
  ie_arquivo              text,
  dt_criacao              timestamptz,
  dt_alteracao            timestamptz,
  ds_usuario_criacao      text,
  ds_usuario_alteracao    text
);
create index copia_nr_seq_solicitante_idx on copia (nr_seq_solicitante);
create index copia_nr_seq_turma_disciplina_idx on copia (nr_seq_turma_disciplina);
create index copia_nr_seq_formato_papel_idx on copia (nr_seq_formato_papel);
create index copia_nr_seq_tipo_papel_idx on copia (nr_seq_tipo_papel);

create table cc_param_tipos_arquivo_copia (
  nr_sequencia         bigint generated by default as identity primary key check (nr_sequencia = 1),
  ds_regra             text,
  cd_cor               text,
  ie_regra             text,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

-- Acesso: só o servidor (driver pg), como as demais tabelas.
alter table cg_formato_papel enable row level security;
alter table cg_tipo_papel enable row level security;
alter table copia enable row level security;
alter table cc_param_tipos_arquivo_copia enable row level security;
revoke all on cg_formato_papel, cg_tipo_papel, copia, cc_param_tipos_arquivo_copia from anon, authenticated;
revoke all on sequence cg_formato_papel_nr_sequencia_seq, cg_tipo_papel_nr_sequencia_seq, copia_nr_sequencia_seq,
  cc_param_tipos_arquivo_copia_nr_sequencia_seq from anon, authenticated;
