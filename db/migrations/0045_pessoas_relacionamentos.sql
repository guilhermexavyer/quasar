-- Quasar: função "Cadastro de Pessoas" passa a ser "Pessoas e Relacionamentos".
--
-- Dropdown: Pessoas Físicas, Pessoas Jurídicas, Alunos e Colaboradores (vindos de Estrutura
-- Acadêmica), Fornecedores, Prestadores de Serviço e Equipes (novas).
--
--   fornecedor / prestador_servico: Pessoa física ou jurídica, Status (Ativo/Inativo), Data e
--     Motivo do status e Observação. Os colaboradores com "Fornecedor" / "Prestador de serviço"
--     marcado (e os usados como Fornecedor do ativo / Prestador da manutenção) são copiados para
--     as tabelas novas, com as mesmas datas e usuários de criação/alteração; o Fornecedor do
--     ativo (pat_ativo.nr_seq_fornecedor) e o Prestador da manutenção
--     (pat_manutencao.nr_seq_prestador_servico) passam a apontar para elas. Colaborador
--     Desligado vira Inativo (com a data e o motivo do status); os demais, Ativo.
--     Os checkboxes saem de Colaboradores (colunas ie_fornecedor e ie_prestador_servico).
--   equipe: Descrição, Status e Observação.
--   equipe_membro: Membros da equipe — um colaborador, um fornecedor OU um prestador de serviço.
--
-- Parâmetros da matrícula de alunos e de colaboradores acompanham Alunos e Colaboradores:
--   ea_param_matricula_aluno       → pr_param_matricula_aluno
--   ea_param_matricula_colaborador → pr_param_matricula_colaborador
-- (auditoria, exclusões e imagens acompanham o nome novo).
--
-- Perfis: as permissões de Alunos e Colaboradores passam de Estrutura Acadêmica para Pessoas e
-- Relacionamentos (só quem as tinha). Perfil com Estrutura Acadêmica liberada e sem Cadastro de
-- Pessoas passa a ter a função, só com Alunos/Colaboradores. Quem já tinha Cadastro de Pessoas
-- recebe as permissões novas (Fornecedores, Prestadores de Serviço e Equipes).

/* ── Tabelas novas ── */

create table fornecedor (
  nr_sequencia           bigint generated by default as identity primary key,
  nr_seq_pessoa_fisica   bigint references pessoa_fisica (nr_sequencia) on delete restrict,
  nr_seq_pessoa_juridica bigint references pessoa_juridica (nr_sequencia) on delete restrict,
  ie_status              text check (ie_status in ('A', 'I')),
  dt_status              date,
  ds_motivo_status       text,
  ds_observacao          text,
  dt_criacao             timestamptz,
  dt_alteracao           timestamptz,
  ds_usuario_criacao     text,
  ds_usuario_alteracao   text
);
create index fornecedor_nr_seq_pessoa_fisica_idx on fornecedor (nr_seq_pessoa_fisica);
create index fornecedor_nr_seq_pessoa_juridica_idx on fornecedor (nr_seq_pessoa_juridica);

create table prestador_servico (
  nr_sequencia           bigint generated by default as identity primary key,
  nr_seq_pessoa_fisica   bigint references pessoa_fisica (nr_sequencia) on delete restrict,
  nr_seq_pessoa_juridica bigint references pessoa_juridica (nr_sequencia) on delete restrict,
  ie_status              text check (ie_status in ('A', 'I')),
  dt_status              date,
  ds_motivo_status       text,
  ds_observacao          text,
  dt_criacao             timestamptz,
  dt_alteracao           timestamptz,
  ds_usuario_criacao     text,
  ds_usuario_alteracao   text
);
create index prestador_servico_nr_seq_pessoa_fisica_idx on prestador_servico (nr_seq_pessoa_fisica);
create index prestador_servico_nr_seq_pessoa_juridica_idx on prestador_servico (nr_seq_pessoa_juridica);

create table equipe (
  nr_sequencia         bigint generated by default as identity primary key,
  ds_equipe            text,
  ie_status            text check (ie_status in ('A', 'I')),
  ds_observacao        text,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

create table equipe_membro (
  nr_sequencia             bigint generated by default as identity primary key,
  nr_seq_equipe            bigint not null references equipe (nr_sequencia) on delete restrict,
  nr_seq_colaborador       bigint references colaborador (nr_sequencia) on delete restrict,
  nr_seq_fornecedor        bigint references fornecedor (nr_sequencia) on delete restrict,
  nr_seq_prestador_servico bigint references prestador_servico (nr_sequencia) on delete restrict,
  dt_criacao               timestamptz,
  dt_alteracao             timestamptz,
  ds_usuario_criacao       text,
  ds_usuario_alteracao     text,
  -- Um membro é um colaborador, um fornecedor ou um prestador de serviço (no máximo um deles).
  constraint equipe_membro_um_tipo_check check (num_nonnulls(nr_seq_colaborador, nr_seq_fornecedor, nr_seq_prestador_servico) <= 1)
);
create index equipe_membro_nr_seq_equipe_idx on equipe_membro (nr_seq_equipe);
create index equipe_membro_nr_seq_colaborador_idx on equipe_membro (nr_seq_colaborador);
create index equipe_membro_nr_seq_fornecedor_idx on equipe_membro (nr_seq_fornecedor);
create index equipe_membro_nr_seq_prestador_servico_idx on equipe_membro (nr_seq_prestador_servico);

comment on column fornecedor.ds_observacao is 'Observação do fornecedor.';
comment on column prestador_servico.ds_observacao is 'Observação do prestador de serviço.';
comment on column equipe_membro.nr_seq_colaborador is 'Membro colaborador (vazio quando o membro é fornecedor ou prestador de serviço).';
comment on column equipe_membro.nr_seq_fornecedor is 'Membro fornecedor (vazio quando o membro é colaborador ou prestador de serviço).';
comment on column equipe_membro.nr_seq_prestador_servico is 'Membro prestador de serviço (vazio quando o membro é colaborador ou fornecedor).';

/* ── Fornecedores e prestadores de serviço vindos de Colaboradores ── */

create temp table _fornecedor_de on commit drop as
  select c.nr_sequencia as antigo, row_number() over (order by c.nr_sequencia) as novo
    from colaborador c
   where c.ie_fornecedor = 'S'
      or exists (select 1 from pat_ativo a where a.nr_seq_fornecedor = c.nr_sequencia);

insert into fornecedor (nr_sequencia, nr_seq_pessoa_fisica, nr_seq_pessoa_juridica, ie_status, dt_status, ds_motivo_status,
                        dt_criacao, dt_alteracao, ds_usuario_criacao, ds_usuario_alteracao)
  select m.novo, c.nr_seq_pessoa_fisica, c.nr_seq_pessoa_juridica,
         case when c.ie_status = 'D' then 'I' else 'A' end,
         case when c.ie_status = 'D' then c.dt_status end,
         case when c.ie_status = 'D' then c.ds_motivo_status end,
         c.dt_criacao, c.dt_alteracao, c.ds_usuario_criacao, c.ds_usuario_alteracao
    from _fornecedor_de m
    join colaborador c on c.nr_sequencia = m.antigo;
select setval(pg_get_serial_sequence('fornecedor', 'nr_sequencia'), coalesce(max(nr_sequencia), 0) + 1, false) from fornecedor;

create temp table _prestador_de on commit drop as
  select c.nr_sequencia as antigo, row_number() over (order by c.nr_sequencia) as novo
    from colaborador c
   where c.ie_prestador_servico = 'S'
      or exists (select 1 from pat_manutencao m where m.nr_seq_prestador_servico = c.nr_sequencia);

insert into prestador_servico (nr_sequencia, nr_seq_pessoa_fisica, nr_seq_pessoa_juridica, ie_status, dt_status, ds_motivo_status,
                               dt_criacao, dt_alteracao, ds_usuario_criacao, ds_usuario_alteracao)
  select m.novo, c.nr_seq_pessoa_fisica, c.nr_seq_pessoa_juridica,
         case when c.ie_status = 'D' then 'I' else 'A' end,
         case when c.ie_status = 'D' then c.dt_status end,
         case when c.ie_status = 'D' then c.ds_motivo_status end,
         c.dt_criacao, c.dt_alteracao, c.ds_usuario_criacao, c.ds_usuario_alteracao
    from _prestador_de m
    join colaborador c on c.nr_sequencia = m.antigo;
select setval(pg_get_serial_sequence('prestador_servico', 'nr_sequencia'), coalesce(max(nr_sequencia), 0) + 1, false) from prestador_servico;

-- Fornecedor do ativo e Prestador da manutenção: apontam para as tabelas novas.
alter table pat_ativo drop constraint pat_ativo_nr_seq_fornecedor_fkey;
update pat_ativo a set nr_seq_fornecedor = m.novo from _fornecedor_de m where a.nr_seq_fornecedor = m.antigo;
alter table pat_ativo add constraint pat_ativo_nr_seq_fornecedor_fkey
  foreign key (nr_seq_fornecedor) references fornecedor (nr_sequencia) on delete restrict;

alter table pat_manutencao drop constraint pat_manutencao_nr_seq_prestador_servico_fkey;
update pat_manutencao p set nr_seq_prestador_servico = m.novo from _prestador_de m where p.nr_seq_prestador_servico = m.antigo;
alter table pat_manutencao add constraint pat_manutencao_nr_seq_prestador_servico_fkey
  foreign key (nr_seq_prestador_servico) references prestador_servico (nr_sequencia) on delete restrict;

comment on column pat_ativo.nr_seq_fornecedor is 'Fornecedor do ativo (Pessoas e Relacionamentos > Fornecedores).';
comment on column pat_manutencao.nr_seq_prestador_servico is 'Prestador de serviço da manutenção (Pessoas e Relacionamentos > Prestadores de Serviço).';

alter table colaborador drop column ie_fornecedor, drop column ie_prestador_servico;

/* ── Parâmetros da matrícula: Estrutura Acadêmica → Pessoas e Relacionamentos ── */

do $$
declare
  par text[];
  c record;
begin
  foreach par slice 1 in array array[
    array['ea_param_matricula_aluno', 'pr_param_matricula_aluno'],
    array['ea_param_matricula_colaborador', 'pr_param_matricula_colaborador']
  ] loop
    execute format('alter table %I rename to %I', par[1], par[2]);
    execute format('alter sequence %I rename to %I', par[1] || '_nr_sequencia_seq', par[2] || '_nr_sequencia_seq');
    -- Restrições (chave primária, registro único, opções da regra) com o nome novo.
    for c in
      select conname from pg_constraint
       where conrelid = par[2]::regclass and conname like par[1] || '%'
    loop
      execute format('alter table %I rename constraint %I to %I', par[2], c.conname, par[2] || substr(c.conname, length(par[1]) + 1));
    end loop;
    update auditoria set ds_colecao = par[2] where ds_colecao = par[1];
    update exclusao  set ds_colecao = par[2] where ds_colecao = par[1];
    update imagem    set ds_colecao_dono = par[2] where ds_colecao_dono = par[1];
  end loop;
end $$;

/* ── Perfis: permissões de Alunos e Colaboradores mudam de função ── */

do $$
declare
  r record;
  -- Permissões de Alunos e Colaboradores (Estrutura Acadêmica → Pessoas e Relacionamentos).
  movidas_todas text[] := array[
    'acessar_aluno', 'adicionar_aluno', 'ver_aluno', 'editar_aluno', 'gerar_matricula_aluno',
    'alterar_data_ingresso_aluno', 'alterar_status_aluno', 'detalhes_aluno', 'excluir_aluno',
    'acessar_colaborador', 'adicionar_colaborador', 'ver_colaborador', 'editar_colaborador',
    'gerar_matricula_colaborador', 'alterar_data_admissao_colaborador', 'alterar_status_colaborador',
    'assumir_ativos_colaborador', 'excluir_colaborador'];
  -- Permissões novas: Fornecedores, Prestadores de Serviço e Equipes.
  novas text[] := array[
    'acessar_fornecedor', 'adicionar_fornecedor', 'ver_fornecedor', 'editar_fornecedor', 'excluir_fornecedor',
    'acessar_prestador_servico', 'adicionar_prestador_servico', 'ver_prestador_servico', 'editar_prestador_servico', 'excluir_prestador_servico',
    'acessar_equipe', 'adicionar_equipe', 'ver_equipe', 'editar_equipe', 'membros_equipe', 'excluir_equipe'];
  -- Permissões que Cadastro de Pessoas já tinha.
  pessoas text[] := array[
    'acessar_pessoa_fisica', 'adicionar_pessoa_fisica', 'ver_pessoa_fisica', 'editar_pessoa_fisica',
    'detalhes_pessoa_fisica', 'excluir_pessoa_fisica', 'acessar_pessoa_juridica', 'adicionar_pessoa_juridica',
    'ver_pessoa_juridica', 'editar_pessoa_juridica', 'excluir_pessoa_juridica'];
  funcoes jsonb;
  cfg jsonb;
  ea jsonb;
  pf jsonb;
  tem_ea boolean;
  tem_pf boolean;
  movidas text[];
  pf_novo text[];
  funcoes_mudou boolean;
begin
  for r in select nr_sequencia, config_funcoes, config_permissoes, config_permissoes_v from perfil loop
    funcoes := r.config_funcoes;
    if jsonb_typeof(funcoes) = 'string' then funcoes := (funcoes #>> '{}')::jsonb; end if;
    if funcoes is null or jsonb_typeof(funcoes) <> 'array' then funcoes := null; end if;
    cfg := r.config_permissoes;
    if jsonb_typeof(cfg) = 'string' then cfg := (cfg #>> '{}')::jsonb; end if;
    if cfg is null or jsonb_typeof(cfg) <> 'object' then cfg := '{}'::jsonb; end if;

    tem_ea := coalesce(funcoes ? 'estruturaAcademica', false);
    tem_pf := coalesce(funcoes ? 'pessoaFisica', false);
    ea := cfg -> 'estruturaAcademica';
    pf := cfg -> 'pessoaFisica';
    funcoes_mudou := false;

    -- Sem configuração salva na função = tudo liberado.
    if not tem_ea then
      movidas := '{}';
    elsif ea is null or jsonb_typeof(ea) <> 'array' then
      movidas := movidas_todas;
    else
      movidas := array(select x from unnest(movidas_todas) x where ea ? x);
    end if;

    if tem_pf then
      if pf is null or jsonb_typeof(pf) <> 'array' then
        pf_novo := pessoas || novas;
      else
        pf_novo := array(select jsonb_array_elements_text(pf)) || novas;
      end if;
      pf_novo := array(select distinct x from unnest(pf_novo || movidas) x order by x);
      cfg := jsonb_set(cfg, '{pessoaFisica}', to_jsonb(pf_novo));
    elsif cardinality(movidas) > 0 then
      cfg := jsonb_set(cfg, '{pessoaFisica}', to_jsonb(movidas));
      funcoes := coalesce(funcoes, '[]'::jsonb) || '["pessoaFisica"]'::jsonb;
      funcoes_mudou := true;
    end if;

    if ea is not null and jsonb_typeof(ea) = 'array' then
      cfg := jsonb_set(cfg, '{estruturaAcademica}',
        coalesce((select jsonb_agg(x) from jsonb_array_elements_text(ea) x where not x = any(movidas_todas)), '[]'::jsonb));
    end if;

    update perfil
       set config_permissoes = case when cfg = '{}'::jsonb and r.config_permissoes is null then null else cfg end,
           config_funcoes = case when funcoes_mudou then funcoes else config_funcoes end,
           -- Versão 31 do formato das permissões (a tela não migra de novo).
           config_permissoes_v = case when config_permissoes_v = 30 then 31 else config_permissoes_v end
     where nr_sequencia = r.nr_sequencia;
  end loop;
end $$;

