-- Quasar: Controle de Cópias > Parâmetros ganha "'Formato do papel' padrão" e
-- "'Tipo de papel' padrão" (dropdown Valor padrão com os cadastros de Cadastros Gerais;
-- --- = sem valor padrão). O valor escolhido já vem preenchido ao adicionar uma cópia.
--
-- Um registro por parâmetro (nr_sequencia = 1), como os demais. Excluir o formato/tipo
-- de papel usado como padrão apenas limpa o parâmetro (on delete set null).

create table cc_param_formato_papel_padrao (
  nr_sequencia         bigint generated by default as identity primary key check (nr_sequencia = 1),
  nr_seq_formato_papel bigint references cg_formato_papel (nr_sequencia) on delete set null,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

create table cc_param_tipo_papel_padrao (
  nr_sequencia         bigint generated by default as identity primary key check (nr_sequencia = 1),
  nr_seq_tipo_papel    bigint references cg_tipo_papel (nr_sequencia) on delete set null,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

-- Acesso: só o servidor (driver pg), como as demais tabelas.
alter table cc_param_formato_papel_padrao enable row level security;
revoke all on cc_param_formato_papel_padrao from anon, authenticated;
revoke all on sequence cc_param_formato_papel_padrao_nr_sequencia_seq from anon, authenticated;
alter table cc_param_tipo_papel_padrao enable row level security;
revoke all on cc_param_tipo_papel_padrao from anon, authenticated;
revoke all on sequence cc_param_tipo_papel_padrao_nr_sequencia_seq from anon, authenticated;
