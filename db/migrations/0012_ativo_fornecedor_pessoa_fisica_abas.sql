-- Quasar: Patrimônio > Ativos ganha o Fornecedor (colaborador com "Fornecedor" marcado), e
-- Pessoas Físicas passa a ter as abas Residencial, Comercial e Saúde (duplo clique na lista).
--
--   pat_ativo.nr_seq_fornecedor: colaborador fornecedor do ativo (seção Classificação);
--   pessoa_fisica_residencial:   endereço residencial (um registro por pessoa física);
--   pessoa_fisica_comercial:     endereço comercial (um registro por pessoa física);
--   pessoa_fisica_saude:         informações médicas (um registro por pessoa física).
--
-- O endereço e as informações médicas que hoje estão em pessoa_fisica são copiados para
-- pessoa_fisica_residencial e pessoa_fisica_saude. As colunas antigas de pessoa_fisica ficam
-- no banco (legado, sem uso na tela), para que nada seja perdido.
-- As regras de campos dos perfis (Campos x Formulários) desses campos passam para as novas tabelas.

-- ═══ Ativo: fornecedor ═══
alter table pat_ativo add column nr_seq_fornecedor bigint references colaborador (nr_sequencia) on delete restrict;
create index pat_ativo_nr_seq_fornecedor_idx on pat_ativo (nr_seq_fornecedor);

-- ═══ Pessoa física: abas ═══
-- Um registro por pessoa física (unique). Saem junto com a pessoa física (on delete cascade).
create table pessoa_fisica_residencial (
  nr_sequencia         bigint generated by default as identity primary key,
  nr_seq_pessoa_fisica bigint not null unique references pessoa_fisica (nr_sequencia) on delete cascade,
  nr_cep               text,
  ds_endereco          text,
  nr_seq_logradouro    bigint references cg_logradouro (nr_sequencia) on delete restrict,
  nr_endereco          text,
  ds_bairro            text,
  ds_complemento       text,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);
create index pessoa_fisica_residencial_nr_seq_logradouro_idx on pessoa_fisica_residencial (nr_seq_logradouro);

create table pessoa_fisica_comercial (
  nr_sequencia         bigint generated by default as identity primary key,
  nr_seq_pessoa_fisica bigint not null unique references pessoa_fisica (nr_sequencia) on delete cascade,
  nr_cep               text,
  ds_endereco          text,
  nr_seq_logradouro    bigint references cg_logradouro (nr_sequencia) on delete restrict,
  nr_endereco          text,
  ds_bairro            text,
  ds_complemento       text,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);
create index pessoa_fisica_comercial_nr_seq_logradouro_idx on pessoa_fisica_comercial (nr_seq_logradouro);

create table pessoa_fisica_saude (
  nr_sequencia            bigint generated by default as identity primary key,
  nr_seq_pessoa_fisica    bigint not null unique references pessoa_fisica (nr_sequencia) on delete cascade,
  ds_tipo_sanguineo       text,
  ds_alergia              text[],
  ds_medicamento_continuo text[],
  ds_restricao_alimentar  text[],
  ds_necessidade_especial text[],
  ds_observacao_medica    text,
  dt_criacao              timestamptz,
  dt_alteracao            timestamptz,
  ds_usuario_criacao      text,
  ds_usuario_alteracao    text
);

-- Cópia do que já existe em pessoa_fisica (só quem tem algum dado preenchido).
insert into pessoa_fisica_residencial (
  nr_seq_pessoa_fisica, nr_cep, ds_endereco, nr_seq_logradouro, nr_endereco, ds_bairro, ds_complemento,
  dt_criacao, dt_alteracao, ds_usuario_criacao, ds_usuario_alteracao
)
select nr_sequencia, nullif(btrim(nr_cep), ''), nullif(btrim(ds_endereco), ''), nr_seq_logradouro,
       nullif(btrim(nr_endereco), ''), nullif(btrim(ds_bairro), ''), nullif(btrim(ds_complemento), ''),
       coalesce(dt_alteracao, dt_criacao, now()), coalesce(dt_alteracao, dt_criacao, now()),
       coalesce(ds_usuario_alteracao, ds_usuario_criacao), coalesce(ds_usuario_alteracao, ds_usuario_criacao)
  from pessoa_fisica
 where coalesce(btrim(nr_cep), '') <> '' or coalesce(btrim(ds_endereco), '') <> ''
    or nr_seq_logradouro is not null or coalesce(btrim(nr_endereco), '') <> ''
    or coalesce(btrim(ds_bairro), '') <> '' or coalesce(btrim(ds_complemento), '') <> '';

insert into pessoa_fisica_saude (
  nr_seq_pessoa_fisica, ds_tipo_sanguineo, ds_alergia, ds_medicamento_continuo, ds_restricao_alimentar,
  ds_necessidade_especial, ds_observacao_medica, dt_criacao, dt_alteracao, ds_usuario_criacao, ds_usuario_alteracao
)
select nr_sequencia, nullif(btrim(ds_tipo_sanguineo), ''), ds_alergia, ds_medicamento_continuo, ds_restricao_alimentar,
       ds_necessidade_especial, nullif(btrim(ds_observacao_medica), ''),
       coalesce(dt_alteracao, dt_criacao, now()), coalesce(dt_alteracao, dt_criacao, now()),
       coalesce(ds_usuario_alteracao, ds_usuario_criacao), coalesce(ds_usuario_alteracao, ds_usuario_criacao)
  from pessoa_fisica
 where coalesce(btrim(ds_tipo_sanguineo), '') <> '' or coalesce(btrim(ds_observacao_medica), '') <> ''
    or coalesce(array_length(array_remove(ds_alergia, ''), 1), 0) > 0
    or coalesce(array_length(array_remove(ds_medicamento_continuo, ''), 1), 0) > 0
    or coalesce(array_length(array_remove(ds_restricao_alimentar, ''), 1), 0) > 0
    or coalesce(array_length(array_remove(ds_necessidade_especial, ''), 1), 0) > 0;

-- Regras de campos dos perfis: pessoa_fisica.<campo> → nova tabela (residencial e comercial
-- recebem a mesma regra de endereço; saúde recebe as das informações médicas).
update perfil p
   set config_campos = (
     select coalesce(jsonb_object_agg(chave, valor), '{}'::jsonb)
       from (
         select e.key as chave, e.value as valor
           from jsonb_each(p.config_campos) e
          where e.key not in (
            'pessoa_fisica.nr_cep', 'pessoa_fisica.ds_endereco', 'pessoa_fisica.nr_seq_logradouro',
            'pessoa_fisica.nr_endereco', 'pessoa_fisica.ds_bairro', 'pessoa_fisica.ds_complemento',
            'pessoa_fisica.ds_tipo_sanguineo', 'pessoa_fisica.ds_alergia', 'pessoa_fisica.ds_medicamento_continuo',
            'pessoa_fisica.ds_restricao_alimentar', 'pessoa_fisica.ds_necessidade_especial', 'pessoa_fisica.ds_observacao_medica'
          )
         union all
         select t.tabela || '.' || substr(e.key, length('pessoa_fisica.') + 1), e.value
           from jsonb_each(p.config_campos) e
           cross join (values ('pessoa_fisica_residencial'), ('pessoa_fisica_comercial')) t (tabela)
          where e.key in (
            'pessoa_fisica.nr_cep', 'pessoa_fisica.ds_endereco', 'pessoa_fisica.nr_seq_logradouro',
            'pessoa_fisica.nr_endereco', 'pessoa_fisica.ds_bairro', 'pessoa_fisica.ds_complemento'
          )
         union all
         select 'pessoa_fisica_saude.' || substr(e.key, length('pessoa_fisica.') + 1), e.value
           from jsonb_each(p.config_campos) e
          where e.key in (
            'pessoa_fisica.ds_tipo_sanguineo', 'pessoa_fisica.ds_alergia', 'pessoa_fisica.ds_medicamento_continuo',
            'pessoa_fisica.ds_restricao_alimentar', 'pessoa_fisica.ds_necessidade_especial', 'pessoa_fisica.ds_observacao_medica'
          )
       ) x
   )
 where jsonb_typeof(p.config_campos) = 'object'
   and exists (select 1 from jsonb_object_keys(p.config_campos) k where k in (
     'pessoa_fisica.nr_cep', 'pessoa_fisica.ds_endereco', 'pessoa_fisica.nr_seq_logradouro',
     'pessoa_fisica.nr_endereco', 'pessoa_fisica.ds_bairro', 'pessoa_fisica.ds_complemento',
     'pessoa_fisica.ds_tipo_sanguineo', 'pessoa_fisica.ds_alergia', 'pessoa_fisica.ds_medicamento_continuo',
     'pessoa_fisica.ds_restricao_alimentar', 'pessoa_fisica.ds_necessidade_especial', 'pessoa_fisica.ds_observacao_medica'
   ));

-- Acesso: só o servidor (driver pg), como as demais tabelas.
alter table pessoa_fisica_residencial enable row level security;
alter table pessoa_fisica_comercial enable row level security;
alter table pessoa_fisica_saude enable row level security;
revoke all on pessoa_fisica_residencial, pessoa_fisica_comercial, pessoa_fisica_saude from anon, authenticated;
revoke all on sequence pessoa_fisica_residencial_nr_sequencia_seq, pessoa_fisica_comercial_nr_sequencia_seq, pessoa_fisica_saude_nr_sequencia_seq from anon, authenticated;
