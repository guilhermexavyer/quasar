-- Quasar: responsáveis do aluno em tabela própria (aluno_responsavel).
--
-- Antes, os responsáveis ficavam dentro do aluno (coluna jsonb responsaveis,
-- uma lista de { nr_seq_responsavel, nr_seq_grau_parentesco }, e nas colunas
-- legadas nr_seq_responsavel / nr_seq_grau_parentesco) e eram editados no
-- formulário do aluno. Agora cada responsável é uma linha de aluno_responsavel,
-- cadastrada com duplo clique no aluno (aba Responsáveis), como os
-- responsáveis de um ativo:
--   nr_seq_aluno           → aluno;
--   nr_seq_pessoa_fisica   → pessoa física responsável;
--   nr_seq_grau_parentesco → grau de parentesco.
--
-- Nenhuma informação se perde:
--   1. cada responsável da lista (ou das colunas legadas) vira uma linha, na
--      mesma ordem, com a autoria/datas do aluno;
--   2. as regras de campo dos perfis (aluno.nr_seq_responsavel e
--      aluno.nr_seq_grau_parentesco) passam para aluno_responsavel.*;
--   3. a quantidade copiada é conferida; só então as colunas antigas saem.
-- Tudo roda numa transação: se qualquer passo falhar, nada é alterado.

create table aluno_responsavel (
  nr_sequencia           bigint generated by default as identity primary key,
  nr_seq_aluno           bigint not null references aluno (nr_sequencia) on delete restrict,
  nr_seq_pessoa_fisica   bigint references pessoa_fisica (nr_sequencia) on delete restrict,
  nr_seq_grau_parentesco bigint references cg_grau_parentesco (nr_sequencia) on delete restrict,
  dt_criacao             timestamptz,
  dt_alteracao           timestamptz,
  ds_usuario_criacao     text,
  ds_usuario_alteracao   text
);
create index aluno_responsavel_nr_seq_aluno_idx on aluno_responsavel (nr_seq_aluno);
create index aluno_responsavel_nr_seq_pessoa_fisica_idx on aluno_responsavel (nr_seq_pessoa_fisica);
create index aluno_responsavel_nr_seq_grau_parentesco_idx on aluno_responsavel (nr_seq_grau_parentesco);

-- ═══ 1. Responsáveis atuais → aluno_responsavel ═══

create temporary table _resp_aluno on commit drop as
-- Lista jsonb (formato atual), na ordem em que aparece no formulário.
select a.nr_sequencia as nr_seq_aluno,
       nullif(e.item ->> 'nr_seq_responsavel', '')::bigint as nr_seq_pessoa_fisica,
       nullif(e.item ->> 'nr_seq_grau_parentesco', '')::bigint as nr_seq_grau_parentesco,
       e.ordem,
       a.dt_criacao, a.dt_alteracao, a.ds_usuario_criacao, a.ds_usuario_alteracao
  from aluno a
  cross join lateral jsonb_array_elements(a.responsaveis) with ordinality as e(item, ordem)
 where jsonb_typeof(a.responsaveis) = 'array'
   and (nullif(e.item ->> 'nr_seq_responsavel', '') is not null or nullif(e.item ->> 'nr_seq_grau_parentesco', '') is not null)
union all
-- Colunas legadas (alunos que nunca tiveram a lista).
select a.nr_sequencia, a.nr_seq_responsavel, a.nr_seq_grau_parentesco, 1,
       a.dt_criacao, a.dt_alteracao, a.ds_usuario_criacao, a.ds_usuario_alteracao
  from aluno a
 where (a.responsaveis is null or jsonb_typeof(a.responsaveis) <> 'array' or jsonb_array_length(a.responsaveis) = 0)
   and (a.nr_seq_responsavel is not null or a.nr_seq_grau_parentesco is not null);

insert into aluno_responsavel (nr_seq_aluno, nr_seq_pessoa_fisica, nr_seq_grau_parentesco, dt_criacao, dt_alteracao, ds_usuario_criacao, ds_usuario_alteracao)
select nr_seq_aluno, nr_seq_pessoa_fisica, nr_seq_grau_parentesco, dt_criacao, dt_alteracao, ds_usuario_criacao, ds_usuario_alteracao
  from _resp_aluno
 order by nr_seq_aluno, ordem;

do $$
declare
  esperados bigint;
  copiados bigint;
  diferencas bigint;
begin
  select count(*) into esperados from _resp_aluno;
  select count(*) into copiados from aluno_responsavel;
  select count(*) into diferencas from (
    (select nr_seq_aluno, nr_seq_pessoa_fisica, nr_seq_grau_parentesco from _resp_aluno
     except all
     select nr_seq_aluno, nr_seq_pessoa_fisica, nr_seq_grau_parentesco from aluno_responsavel)
    union all
    (select nr_seq_aluno, nr_seq_pessoa_fisica, nr_seq_grau_parentesco from aluno_responsavel
     except all
     select nr_seq_aluno, nr_seq_pessoa_fisica, nr_seq_grau_parentesco from _resp_aluno)
  ) d;
  if esperados <> copiados or diferencas > 0 then
    raise exception 'aluno_responsavel: cópia divergente (% esperados, % copiados, % diferença(s)). Nada foi alterado.', esperados, copiados, diferencas;
  end if;
  raise notice 'aluno_responsavel: % responsável(is) copiado(s) e conferido(s).', copiados;
end $$;

-- ═══ 2. Regras de campo dos perfis ═══

update perfil
   set config_campos = (config_campos - 'aluno.nr_seq_responsavel' - 'aluno.nr_seq_grau_parentesco')
       || case when config_campos ? 'aluno.nr_seq_responsavel'
               then jsonb_build_object('aluno_responsavel.nr_seq_pessoa_fisica', config_campos -> 'aluno.nr_seq_responsavel') else '{}'::jsonb end
       || case when config_campos ? 'aluno.nr_seq_grau_parentesco'
               then jsonb_build_object('aluno_responsavel.nr_seq_grau_parentesco', config_campos -> 'aluno.nr_seq_grau_parentesco') else '{}'::jsonb end
 where jsonb_typeof(config_campos) = 'object'
   and (config_campos ? 'aluno.nr_seq_responsavel' or config_campos ? 'aluno.nr_seq_grau_parentesco');

update perfil
   set config_campos_alteracao = (config_campos_alteracao - 'aluno.nr_seq_responsavel' - 'aluno.nr_seq_grau_parentesco')
       || case when config_campos_alteracao ? 'aluno.nr_seq_responsavel'
               then jsonb_build_object('aluno_responsavel.nr_seq_pessoa_fisica', config_campos_alteracao -> 'aluno.nr_seq_responsavel') else '{}'::jsonb end
       || case when config_campos_alteracao ? 'aluno.nr_seq_grau_parentesco'
               then jsonb_build_object('aluno_responsavel.nr_seq_grau_parentesco', config_campos_alteracao -> 'aluno.nr_seq_grau_parentesco') else '{}'::jsonb end
 where jsonb_typeof(config_campos_alteracao) = 'object'
   and (config_campos_alteracao ? 'aluno.nr_seq_responsavel' or config_campos_alteracao ? 'aluno.nr_seq_grau_parentesco');

-- Permissão nova "detalhes_aluno" (duplo clique no aluno → Responsáveis):
-- quem já via ou adicionava alunos editava os responsáveis no formulário,
-- então continua podendo. Perfis sem configuração salva já liberam tudo.
update perfil
   set config_permissoes = jsonb_set(config_permissoes, '{estruturaAcademica}', (config_permissoes -> 'estruturaAcademica') || '["detalhes_aluno"]'::jsonb)
 where jsonb_typeof(config_permissoes -> 'estruturaAcademica') = 'array'
   and ((config_permissoes -> 'estruturaAcademica') ? 'ver_aluno' or (config_permissoes -> 'estruturaAcademica') ? 'adicionar_aluno')
   and not (config_permissoes -> 'estruturaAcademica') ? 'detalhes_aluno';

