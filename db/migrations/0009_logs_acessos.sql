-- Quasar: função "Logs" (Exclusões, que sai de Administração do Sistema, e Acessos).
--
-- 1. log_acesso: um registro por login. O servidor grava ao entrar e completa
--    ao sair (dt_logout e ie_tipo_logout: 'M' = manual, pelo botão Sair;
--    'A' = automático, pela regra de logout de Administração do Sistema > Sistema).
--    Sem logout registrado (aba fechada, sessão expirada) as duas ficam vazias.
--    Usuário e pessoa física são guardados como estavam no login (histórico):
--    nr_seq_usuario e nr_seq_sessao não têm FK, para o log sobreviver à exclusão.
-- 2. Perfis com Administração do Sistema passam a ter também a função Logs:
--    quem via Exclusões continua vendo (as permissões migram na tela, v24).

create table log_acesso (
  nr_sequencia      bigint generated by default as identity primary key,
  nr_seq_usuario    bigint not null,
  nr_seq_sessao     bigint,
  ds_usuario        text not null,
  ds_pessoa_fisica  text,
  dt_login          timestamptz not null default now(),
  dt_logout         timestamptz,
  ie_tipo_logout    text check (ie_tipo_logout in ('M', 'A'))
);
create index log_acesso_nr_seq_usuario_idx on log_acesso (nr_seq_usuario);
create index log_acesso_nr_seq_sessao_idx on log_acesso (nr_seq_sessao);
create index log_acesso_dt_login_idx on log_acesso (dt_login desc);

update perfil
   set config_funcoes = config_funcoes || '["logs"]'::jsonb
 where jsonb_typeof(config_funcoes) = 'array'
   and config_funcoes ? 'administracaoSistema'
   and not config_funcoes ? 'logs';

-- Acesso: só o servidor (driver pg), como as demais tabelas.
alter table log_acesso enable row level security;
revoke all on log_acesso from anon, authenticated;
revoke all on sequence log_acesso_nr_sequencia_seq from anon, authenticated;
