-- Quasar: Controle de Cópias > Cópias ganha datas e status.
--
--   dt_recebimento, dt_impressao, dt_entrega: datas do pedido de cópia;
--   ie_status: Aguardando (A), Cancelado (C), Entregue (E) ou Impresso (I) — escolhido no
--              cadastro; depois, só pelo menu de contexto "Alterar status";
--   dt_status / ds_motivo_status: data e motivo da última alteração de status.
-- Parâmetros (Controle de Cópias > Parâmetros): a cor de cada status na coluna de bolinhas
-- da lista, um registro por parâmetro (como as cores de Patrimônio).

alter table copia
  add column dt_recebimento   date,
  add column dt_impressao     date,
  add column dt_entrega       date,
  add column ie_status        text check (ie_status in ('A', 'C', 'E', 'I')),
  add column dt_status        date,
  add column ds_motivo_status text;

-- Cópias cadastradas antes do status ficam como Aguardando.
update copia set ie_status = 'A' where ie_status is null;

create table cc_param_cor_copia_aguardando (
  nr_sequencia         bigint generated by default as identity primary key check (nr_sequencia = 1),
  ds_regra             text,
  cd_cor               text,
  ie_regra             text,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);
create table cc_param_cor_copia_cancelado (like cc_param_cor_copia_aguardando including all);
create table cc_param_cor_copia_entregue (like cc_param_cor_copia_aguardando including all);
create table cc_param_cor_copia_impresso (like cc_param_cor_copia_aguardando including all);

-- Acesso: só o servidor (driver pg), como as demais tabelas.
alter table cc_param_cor_copia_aguardando enable row level security;
alter table cc_param_cor_copia_cancelado enable row level security;
alter table cc_param_cor_copia_entregue enable row level security;
alter table cc_param_cor_copia_impresso enable row level security;
revoke all on cc_param_cor_copia_aguardando, cc_param_cor_copia_cancelado, cc_param_cor_copia_entregue,
  cc_param_cor_copia_impresso from anon, authenticated;
revoke all on sequence cc_param_cor_copia_aguardando_nr_sequencia_seq, cc_param_cor_copia_cancelado_nr_sequencia_seq,
  cc_param_cor_copia_entregue_nr_sequencia_seq, cc_param_cor_copia_impresso_nr_sequencia_seq from anon, authenticated;
