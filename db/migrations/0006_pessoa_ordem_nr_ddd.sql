-- Quasar: nr_ddd logo antes de nr_telefone em pessoa_fisica e pessoa_juridica.
--
-- O PostgreSQL não muda a posição de uma coluna (a 0005 criou nr_ddd no fim
-- da tabela). Para a ordem ficar certa, as duas tabelas são recriadas:
--   1. as chaves estrangeiras de outras tabelas que apontam para elas são
--      guardadas e retiradas;
--   2. cada tabela é recriada com a ordem nova (mesmas colunas, tipos e
--      regras) e recebe TODOS os registros, com os mesmos nr_sequencia;
--   3. os dados novos são comparados com os antigos, linha a linha e coluna a
--      coluna — qualquer diferença para a migração (nada muda);
--   4. a tabela antiga sai; índices, regras, chaves estrangeiras, numeração
--      automática, RLS e permissões são refeitos.
-- Tudo roda numa transação: se qualquer passo falhar, nada é alterado.

-- ═══ 1. Chaves estrangeiras que apontam para as tabelas de pessoa ═══

create temporary table _fk_pessoa on commit drop as
select c.conrelid::regclass::text as tabela, c.conname as nome, pg_get_constraintdef(c.oid) as definicao
  from pg_constraint c
 where c.contype = 'f'
   and c.confrelid in ('pessoa_fisica'::regclass, 'pessoa_juridica'::regclass)
   and c.conrelid not in ('pessoa_fisica'::regclass, 'pessoa_juridica'::regclass);

do $$
declare
  fk record;
begin
  for fk in select * from _fk_pessoa loop
    execute format('alter table %s drop constraint %I', fk.tabela, fk.nome);
  end loop;
end $$;

