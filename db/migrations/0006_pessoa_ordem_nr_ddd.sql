-- ═══ 3. Cópia dos registros (por nome de coluna) e conferência ═══

do $$
declare
  t text;
  colunas text;
  qt_antiga bigint;
  qt_nova bigint;
  diferencas bigint;
begin
  foreach t in array array['pessoa_fisica', 'pessoa_juridica'] loop
    -- As colunas das duas tabelas têm de ser exatamente as mesmas (nome e tipo).
    select count(*) into diferencas from (
      (select column_name, data_type, udt_name from information_schema.columns where table_schema = 'public' and table_name = t
       except
       select column_name, data_type, udt_name from information_schema.columns where table_schema = 'public' and table_name = t || '_nova')
      union all
      (select column_name, data_type, udt_name from information_schema.columns where table_schema = 'public' and table_name = t || '_nova'
       except
       select column_name, data_type, udt_name from information_schema.columns where table_schema = 'public' and table_name = t)
    ) d;
    if diferencas > 0 then
      raise exception '%: a tabela nova não tem as mesmas colunas da atual. Nada foi alterado.', t;
    end if;

    select string_agg(format('%I', column_name), ', ' order by ordinal_position) into colunas
      from information_schema.columns where table_schema = 'public' and table_name = t || '_nova';

    execute format('insert into %I (%s) overriding system value select %s from %I', t || '_nova', colunas, colunas, t);

    execute format('select count(*) from %I', t) into qt_antiga;
    execute format('select count(*) from %I', t || '_nova') into qt_nova;
    execute format(
      'select count(*) from ((select %1$s from %2$I except all select %1$s from %3$I) union all (select %1$s from %3$I except all select %1$s from %2$I)) d',
      colunas, t, t || '_nova') into diferencas;
    if qt_antiga <> qt_nova or diferencas > 0 then
      raise exception '%: cópia divergente (% registros na atual, % na nova, % diferença(s)). Nada foi alterado.', t, qt_antiga, qt_nova, diferencas;
    end if;
    raise notice '%: % registro(s) copiado(s) e conferido(s).', t, qt_nova;
  end loop;
end $$;

-- ═══ 4. Troca das tabelas e reconstrução de tudo o que dependia delas ═══

drop table pessoa_fisica;
drop table pessoa_juridica;
alter table pessoa_fisica_nova rename to pessoa_fisica;
alter table pessoa_juridica_nova rename to pessoa_juridica;
alter sequence pessoa_fisica_nova_nr_sequencia_seq rename to pessoa_fisica_nr_sequencia_seq;
alter sequence pessoa_juridica_nova_nr_sequencia_seq rename to pessoa_juridica_nr_sequencia_seq;

-- A numeração automática continua de onde parou.
select setval('pessoa_fisica_nr_sequencia_seq', coalesce((select max(nr_sequencia) from pessoa_fisica), 1), (select count(*) > 0 from pessoa_fisica));
select setval('pessoa_juridica_nr_sequencia_seq', coalesce((select max(nr_sequencia) from pessoa_juridica), 1), (select count(*) > 0 from pessoa_juridica));

alter table pessoa_fisica
  add constraint pessoa_fisica_pkey primary key (nr_sequencia),
  add constraint pessoa_fisica_nr_seq_sexo_fkey foreign key (nr_seq_sexo) references cg_sexo (nr_sequencia) on delete restrict,
  add constraint pessoa_fisica_nr_seq_estado_civil_fkey foreign key (nr_seq_estado_civil) references cg_estado_civil (nr_sequencia) on delete restrict,
  add constraint pessoa_fisica_nr_seq_cor_raca_fkey foreign key (nr_seq_cor_raca) references cg_cor_raca (nr_sequencia) on delete restrict,
  add constraint pessoa_fisica_nr_seq_profissao_fkey foreign key (nr_seq_profissao) references cg_profissao (nr_sequencia) on delete restrict,
  add constraint pessoa_fisica_nr_seq_orgao_emissor_fkey foreign key (nr_seq_orgao_emissor) references cg_orgao_emissor (nr_sequencia) on delete restrict,
  add constraint pessoa_fisica_nr_seq_logradouro_fkey foreign key (nr_seq_logradouro) references cg_logradouro (nr_sequencia) on delete restrict,
  add constraint pessoa_fisica_nr_cpf_digitos check (nr_cpf ~ '^\d{11}$'),
  add constraint pessoa_fisica_nr_ddd_digitos check (nr_ddd ~ '^\d{2}$'),
  add constraint pessoa_fisica_nr_telefone_digitos check (nr_telefone ~ '^\d{8,9}$'),
  add constraint pessoa_fisica_telefone_com_ddd check ((nr_ddd is null) = (nr_telefone is null));

alter table pessoa_juridica
  add constraint pessoa_juridica_pkey primary key (nr_sequencia),
  add constraint pessoa_juridica_nr_seq_logradouro_fkey foreign key (nr_seq_logradouro) references cg_logradouro (nr_sequencia) on delete restrict,
  add constraint pessoa_juridica_nr_ddd_digitos check (nr_ddd ~ '^\d{2}$'),
  add constraint pessoa_juridica_nr_telefone_digitos check (nr_telefone ~ '^\d{8,9}$'),
  add constraint pessoa_juridica_telefone_com_ddd check ((nr_ddd is null) = (nr_telefone is null));

create index pessoa_fisica_nr_seq_sexo_idx on pessoa_fisica (nr_seq_sexo);
create index pessoa_fisica_nr_seq_estado_civil_idx on pessoa_fisica (nr_seq_estado_civil);
create index pessoa_fisica_nr_seq_cor_raca_idx on pessoa_fisica (nr_seq_cor_raca);
create index pessoa_fisica_nr_seq_profissao_idx on pessoa_fisica (nr_seq_profissao);
create index pessoa_fisica_nr_seq_orgao_emissor_idx on pessoa_fisica (nr_seq_orgao_emissor);
create index pessoa_fisica_nr_seq_logradouro_idx on pessoa_fisica (nr_seq_logradouro);
create index pessoa_juridica_nr_seq_logradouro_idx on pessoa_juridica (nr_seq_logradouro);

