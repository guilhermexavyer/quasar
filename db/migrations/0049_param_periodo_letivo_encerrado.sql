-- Quasar: Administração do Sistema > Parâmetros ganha quatro parâmetros Sim/Não sobre
-- o período letivo encerrado (--- ou Não = não permite):
--   Estrutura Acadêmica > Período letivo:
--     "Permitir feriados em período letivo encerrado" (adicionar, alterar e excluir)
--       → periodo_letivo_param_feriado_encerrado
--   Estrutura Acadêmica > Turmas:
--     "Permitir período letivo encerrado na turma"
--       → turma_param_periodo_letivo_encerrado
--   Estrutura Acadêmica > Turmas x Disciplinas:
--     "Permitir turma com período letivo encerrado"
--       → turma_disciplina_param_periodo_encerrado
--   Controle de Cópias > Cópias:
--     "Permitir turma x disciplina com período letivo encerrado"
--       → copia_param_periodo_letivo_encerrado
--
-- Um registro por parâmetro (nr_sequencia = 1), como os demais; o valor fica em ie_regra ('S'/'N').

create table periodo_letivo_param_feriado_encerrado (
  nr_sequencia         bigint generated by default as identity primary key check (nr_sequencia = 1),
  ie_regra             text,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

create table turma_param_periodo_letivo_encerrado (
  nr_sequencia         bigint generated by default as identity primary key check (nr_sequencia = 1),
  ie_regra             text,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

create table turma_disciplina_param_periodo_encerrado (
  nr_sequencia         bigint generated by default as identity primary key check (nr_sequencia = 1),
  ie_regra             text,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

create table copia_param_periodo_letivo_encerrado (
  nr_sequencia         bigint generated by default as identity primary key check (nr_sequencia = 1),
  ie_regra             text,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

-- Acesso: só o servidor (driver pg), como as demais tabelas.
alter table periodo_letivo_param_feriado_encerrado enable row level security;
revoke all on periodo_letivo_param_feriado_encerrado from anon, authenticated;
revoke all on sequence periodo_letivo_param_feriado_encerrado_nr_sequencia_seq from anon, authenticated;
alter table turma_param_periodo_letivo_encerrado enable row level security;
revoke all on turma_param_periodo_letivo_encerrado from anon, authenticated;
revoke all on sequence turma_param_periodo_letivo_encerrado_nr_sequencia_seq from anon, authenticated;
alter table turma_disciplina_param_periodo_encerrado enable row level security;
revoke all on turma_disciplina_param_periodo_encerrado from anon, authenticated;
revoke all on sequence turma_disciplina_param_periodo_encerrado_nr_sequencia_seq from anon, authenticated;
alter table copia_param_periodo_letivo_encerrado enable row level security;
revoke all on copia_param_periodo_letivo_encerrado from anon, authenticated;
revoke all on sequence copia_param_periodo_letivo_encerrado_nr_sequencia_seq from anon, authenticated;
