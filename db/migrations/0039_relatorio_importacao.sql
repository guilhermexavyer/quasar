-- Quasar: Gerenciador de Relatórios > Importar relatório.
--
-- Também: o elemento aceita as máscaras CEP, CPF e CNPJ (no fim do arquivo).
--
-- Cada importação de um arquivo .xml exportado por outro ambiente (Exportar relatório) fica
-- registrada aqui. O relatório criado tem Origem 'I' (Importação).
--
--   * ds_arquivo         Nome do arquivo importado.
--   * nr_seq_relatorio   Relatório criado pela importação (vazio se ele for excluído depois).
--   * ds_relatorio       Descrição do relatório no arquivo.
--   * ds_versao_sistema  Versão do Quasar que exportou o arquivo.
--   * dt_exportacao      Quando o arquivo foi exportado.
--   * qt_bandas, qt_elementos, qt_parametros  Quantidades criadas.
--   * ds_xml             Conteúdo do arquivo (para consulta).

create table relatorio_importacao (
  nr_sequencia         bigint generated by default as identity primary key,
  ds_arquivo           text,
  nr_seq_relatorio     bigint references relatorio (nr_sequencia) on delete set null,
  ds_relatorio         text,
  ds_versao_sistema    text,
  dt_exportacao        timestamptz,
  qt_bandas            integer,
  qt_elementos         integer,
  qt_parametros        integer,
  ds_xml               text,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);
create index relatorio_importacao_nr_seq_relatorio_idx on relatorio_importacao (nr_seq_relatorio);
-- Acesso: só o servidor (driver pg), como as demais tabelas.
alter table relatorio_importacao enable row level security;
revoke all on relatorio_importacao from anon, authenticated;
revoke all on sequence relatorio_importacao_nr_sequencia_seq from anon, authenticated;

comment on table relatorio_importacao is 'Importações de relatórios (Gerenciador de Relatórios > Importar relatório).';
comment on column relatorio_importacao.ds_arquivo is 'Nome do arquivo .xml importado.';
comment on column relatorio_importacao.nr_seq_relatorio is 'Relatório criado pela importação.';
comment on column relatorio_importacao.ds_relatorio is 'Descrição do relatório no arquivo.';
comment on column relatorio_importacao.ds_versao_sistema is 'Versão do Quasar que exportou o arquivo.';
comment on column relatorio_importacao.dt_exportacao is 'Data e hora da exportação.';
comment on column relatorio_importacao.ds_xml is 'Conteúdo do arquivo importado.';

-- Máscaras CEP, CPF e CNPJ do elemento (a tela já oferece; o banco ainda não aceitava).
alter table relatorio_banda_elemento drop constraint if exists relatorio_banda_elemento_ie_mascara_check;
alter table relatorio_banda_elemento add constraint relatorio_banda_elemento_ie_mascara_check
  check (ie_mascara in ('cep', 'cnpj', 'cpf', 'data', 'data_hora', 'hora', 'moeda', 'numero', 'porcentagem'));
