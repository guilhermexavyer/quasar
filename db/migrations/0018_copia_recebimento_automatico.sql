-- Quasar: Controle de Cópias > Parâmetros ganha "'Data de recebimento' é automaticamente
-- preenchido com a data atual" (Sim/Não em ie_regra; --- equivale a Não). Com Sim, o
-- formulário de uma cópia nova já abre com a Data do recebimento = hoje.

create table cc_param_data_recebimento_automatica (
  nr_sequencia         bigint generated by default as identity primary key check (nr_sequencia = 1),
  ds_regra             text,
  cd_cor               text,
  ie_regra             text,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text
);

-- Acesso: só o servidor (driver pg), como as demais tabelas.
alter table cc_param_data_recebimento_automatica enable row level security;
revoke all on cc_param_data_recebimento_automatica from anon, authenticated;
revoke all on sequence cc_param_data_recebimento_automatica_nr_sequencia_seq from anon, authenticated;
