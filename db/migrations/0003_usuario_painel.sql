-- Quasar: largura dos painéis em tabela própria.
--
-- Algumas telas têm painéis lado a lado que o usuário redimensiona com o mouse
-- (Avisos, Regras, Campos, Exclusões e Parâmetros da função). A largura de cada
-- um ficava em colunas config_paineis_* da tabela usuario. Agora cada tela de
-- cada usuário é uma linha de usuario_painel:
--   ie_tela         → identificador da tela (o sufixo do antigo config_paineis_*,
--                     ex.: avisos, regras, parametros_funcao_ea);
--   config_paineis  → a configuração salva (larguras), em jsonb.
-- A API continua entregando config_paineis_<ie_tela> no objeto do usuário,
-- então as telas não mudam.
--
-- As preferências pertencem ao usuário: ao excluí-lo, elas saem junto (cascade).
-- Os dados existentes em usuario.config_paineis_* são copiados antes de as
-- colunas antigas serem removidas.

create table usuario_painel (
  nr_sequencia         bigint generated by default as identity primary key,
  nr_seq_usuario       bigint not null references usuario (nr_sequencia) on delete cascade,
  ie_tela              text   not null check (ie_tela ~ '^[a-z0-9_]+$'),
  config_paineis       jsonb  not null,
  dt_criacao           timestamptz,
  dt_alteracao         timestamptz,
  ds_usuario_criacao   text,
  ds_usuario_alteracao text,
  unique (nr_seq_usuario, ie_tela)
);

do $$
declare
  coluna text;
begin
  for coluna in
    select column_name from information_schema.columns
     where table_schema = 'public' and table_name = 'usuario' and column_name like 'config\_paineis\_%'
     order by column_name
  loop
    execute format(
      'insert into usuario_painel (nr_seq_usuario, ie_tela, config_paineis, dt_criacao, dt_alteracao, ds_usuario_criacao, ds_usuario_alteracao)
       select nr_sequencia, %L, %I, now(), now(), ds_usuario, ds_usuario from usuario where %I is not null',
      substr(coluna, length('config_paineis_') + 1), coluna, coluna
    );
    execute format('alter table usuario drop column %I', coluna);
  end loop;
end $$;

alter table usuario_painel enable row level security;
revoke all on usuario_painel from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;
